#!/usr/bin/env python3
# Genera los PNG de los vaqueros a partir de dibujos en texto.
#
# Cada dibujo mide 16x20 "píxeles gordos" y se amplía x2, así que cada PNG
# queda de 32x40 píxeles (en modo 1: 8 bytes de ancho x 40 líneas).
# Los del enemigo son el espejo de los del jugador, con la ropa en otro color.
#
# Uso (desde esta carpeta):  python3 sprites.py
# Después, al hacer make, CPCtelera convierte los PNG en arrays de C.
#
# Leyenda (los 4 colores del modo 1, ver cfg/image_conversion.mk):
#   .  color 0  negro   (fondo)
#   o  color 1  naranja (piel)
#   r  color 2  rojo    (camisa, fogonazo)
#   w  color 3  blanco  (sombrero, pantalón, pistola)

import struct
import zlib

# Colores RGB exactos de la paleta del CPC (firmware 0, 15, 6 y 26)
RGB = {
    '.': (0, 0, 0),
    'o': (255, 128, 0),
    'r': (255, 0, 0),
    'w': (255, 255, 255),
}

