def pixeles(dibujo, espejo=False, cambiar_ropa=False):
    filas = [f for f in dibujo.strip().split('\n')]
    assert len(filas) == 20 and all(len(f) == 16 for f in filas), "el dibujo debe ser 16x20"
    if espejo:
        filas = [f[::-1] for f in filas]
    if cambiar_ropa:  # el enemigo: lo rojo pasa a blanco y lo blanco a rojo
        filas = [f.translate(str.maketrans('rw', 'wr')) for f in filas]
    # Ampliar x2 en horizontal y en vertical
    grande = []
    for f in filas:
        linea = [RGB[c] for c in f for _ in range(2)]
        grande += [linea, linea]
    return grande


def guardar_png(nombre, filas):
    alto, ancho = len(filas), len(filas[0])
    crudo = b''.join(b'\x00' + bytes(v for p in fila for v in p) for fila in filas)

    def bloque(tipo, datos):
        return (struct.pack('>I', len(datos)) + tipo + datos
                + struct.pack('>I', zlib.crc32(tipo + datos) & 0xffffffff))

    with open(nombre, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n')
        f.write(bloque(b'IHDR', struct.pack('>IIBBBBB', ancho, alto, 8, 2, 0, 0, 0)))
        f.write(bloque(b'IDAT', zlib.compress(crudo)))
        f.write(bloque(b'IEND', b''))
    print('generado', nombre)


for nombre, dibujo in (('q', QUIETO), ('d', DISPARA), ('m', MUERTO)):
    guardar_png('jug' + nombre + '.png', pixeles(dibujo))
    guardar_png('ene' + nombre + '.png', pixeles(dibujo, espejo=True, cambiar_ropa=True))
